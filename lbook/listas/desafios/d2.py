lugares = ['Los Angeles', 'Paris', 'Foz do Iguaçu']
print(lugares)
ordem_alfa = sorted(lugares) # retorna a lista em ordem alfabética
print(ordem_alfa)

print(lugares)

ordem_inversa = sorted(lugares, reverse=True) # retorna a ordem da lista inversa
print(ordem_inversa)

print(lugares)

lugares.reverse() # muda a ordem da lista
print(lugares)

lugares.reverse() # volta a ordem original da lista
print(lugares)

lugares.sort() # retorna a lista em ordem alfabética
print(lugares)

lugares.sort(reverse=True) # retorna a ordem alfabética reversa da lista
print(lugares)

print(len(lugares)) # retorna a quantidade de elementos dentro da lista

