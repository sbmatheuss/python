# reerser() -> inverte a ordem original de uma lista permanentemente
# (pode-se restautrar a ordem original aplicando o reverse() a mesma lista)

cars = ['BMW', 'ADUID', 'TOYOTA']
cars.reverse() # inverte a ordem da lista permanentemente
print(cars)

